/**
 * PokeAPI type-effectiveness chart generator for Pixelmon.
 *
 * Fetches the damage relations for all 18 types from https://pokeapi.co and
 * emits an authoritative 18x18 matrix as C++:
 *
 *   src/core/type_chart.inc
 *
 * The matrix is indexed by the ORDER of the pm::Type enum in src/types.hpp
 * (row = attacker, column = defender). Values are single-type multipliers:
 *   1.0 = normal, 2.0 = super effective, 0.5 = not very effective, 0.0 = no effect.
 * Dual-type defenders stack these (handled in the battle system), so this chart
 * stays a clean per-type table.
 *
 * Usage: node scripts/generate-type-chart.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const API = "https://pokeapi.co/api/v2";
const OUT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../src/core/type_chart.inc"
);

// Must match the pm::Type enum order in src/types.hpp exactly.
const TYPES = [
  "normal", "fire", "water", "grass", "electric", "ice", "fighting", "poison",
  "ground", "flying", "psychic", "bug", "rock", "ghost", "dragon", "dark",
  "fairy", "steel",
];
const TYPE_NAMES = TYPES.map((t) => t.charAt(0).toUpperCase() + t.slice(1));

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function fetchJson(url, retries = 3) {
  for (let attempt = 0; attempt <= retries; attempt++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return await res.json();
    } catch (err) {
      if (attempt === retries) throw err;
      console.error(`  retry ${attempt + 1} for ${url}: ${err.message}`);
      await sleep(1500 * (attempt + 1));
    }
  }
}

async function main() {
  const idx = new Map(TYPES.map((t, i) => [t, i]));
  // row = attacker, col = defender
  const matrix = Array.from({ length: 18 }, () => new Array(18).fill(1.0));

  for (const attacker of TYPES) {
    const data = await fetchJson(`${API}/type/${attacker}`);
    const rel = data.damage_relations ?? {};
    const doubles = new Set((rel.double_damage_to ?? []).map((x) => x.name));
    const halves = new Set((rel.half_damage_to ?? []).map((x) => x.name));
    const none = new Set((rel.no_damage_to ?? []).map((x) => x.name));
    const r = idx.get(attacker);
    for (const defender of TYPES) {
      const c = idx.get(defender);
      if (doubles.has(defender)) matrix[r][c] = 2.0;
      else if (halves.has(defender)) matrix[r][c] = 0.5;
      else if (none.has(defender)) matrix[r][c] = 0.0;
      else matrix[r][c] = 1.0;
    }
    console.log(`  ${attacker} done`);
  }

  const lines = [];
  lines.push("// AUTO-GENERATED by scripts/generate-type-chart.mjs — do not edit by hand.");
  lines.push("// Source: https://pokeapi.co/api/v2/type (damage relations).");
  lines.push(`// Order: ${TYPE_NAMES.join(", ")}`);
  lines.push("namespace pm {");
  lines.push("// typeChart()[attacker][defender] — see src/types.hpp for enum order.");
  lines.push("const double g_TypeChart[18][18] = {");
  for (const row of matrix) {
    lines.push("  { " + row.map((v) => v.toFixed(1)).join(", ") + " },");
  }
  lines.push("};");
  lines.push("}  // namespace pm");
  lines.push("");

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, lines.join("\n"));
  console.log(`\n=== DONE ===`);
  console.log(`wrote ${OUT}`);
  console.log(`normal->rock: ${matrix[idx.get("normal")][idx.get("rock")]} (expect 0.5)`);
  console.log(`fire->grass: ${matrix[idx.get("fire")][idx.get("grass")]} (expect 2.0)`);
  console.log(`water->fire: ${matrix[idx.get("water")][idx.get("fire")]} (expect 2.0)`);
  console.log(`ghost->normal: ${matrix[idx.get("ghost")][idx.get("normal")]} (expect 0.0)`);
}

main().catch((err) => {
  console.error("FATAL:", err);
  process.exit(1);
});
